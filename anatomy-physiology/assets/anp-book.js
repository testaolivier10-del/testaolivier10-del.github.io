/* The Learn tab as a textbook, like ochem's Learn (spec decision 67).

   The contents rail (generated by build-anp.mjs) lists every chapter and its
   topics. This shows one chapter in the main column: its header, then each
   built topic's notes one after another, taken from the topic's own notes page
   (the article.anp-prose), so the prose has one source. Pages are fetched when
   a chapter opens, in parallel, and each fills its place as it arrives.

   #<chapter> opens a chapter, #<topic> opens its chapter at that topic. With
   no hash the last chapter read comes back (anp_book_last), else chapter 1.
   Without JavaScript none of this runs, and the main column stays a table of
   contents whose links go to the notes pages. */
(function(){
  var CU = window.AnpCurriculum;
  var book = document.getElementById('anp-book');
  var rail = document.getElementById('anp-rail');
  if(!CU || !book || !rail) return;
  var LAST = 'anp_book_last';

  var chapters = CU.chapters, topics = CU.topics;
  var chById = {}, tById = {};
  chapters.forEach(function(c){ chById[c.id] = c; });
  topics.forEach(function(t){ tById[t.id] = t; });
  var partTitle = {};
  (CU.parts || []).forEach(function(p){ partTitle[p.id] = p.title; });
  function builtOf(chId){ return topics.filter(function(t){ return t.chapter === chId && t.built; }); }
  function esc(s){ return String(s == null ? '' : s).replace(/[&<>"]/g, function(c){ return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
  function store(k, v){ try{ if(v === undefined) return localStorage.getItem(k); localStorage.setItem(k, v); }catch(e){ return null; } }

  /* One topic's prose from its notes page. Relative links and images are
     rewritten against that page's address, and every id (and the #links to
     it) gets the topic as a prefix, because a chapter holds many topics that
     each have a "summary" or a "fig-..." of their own. */
  var cache = {};
  function prose(id){
    if(cache[id]) return cache[id];
    var url = new URL('notes/' + id + '.html', location.href);
    cache[id] = fetch(url.href).then(function(r){
      if(!r.ok) throw new Error('HTTP ' + r.status);
      return r.text();
    }).then(function(html){
      var doc = new DOMParser().parseFromString(html, 'text/html');
      var art = doc.querySelector('article.anp-prose');
      if(!art) throw new Error('no prose');
      art.querySelectorAll('[href],[src]').forEach(function(el){
        ['href', 'src'].forEach(function(a){
          var v = el.getAttribute(a);
          if(!v) return;
          if(v.charAt(0) === '#') el.setAttribute(a, '#' + id + '--' + v.slice(1));
          else if(!/^[a-z]+:/i.test(v)){ var u = new URL(v, url); el.setAttribute(a, u.pathname + u.search + u.hash); }
        });
      });
      art.querySelectorAll('[id]').forEach(function(el){ el.id = id + '--' + el.id; });
      // The topic title is this section's h2, so the notes' own headings step down one.
      art.querySelectorAll('h3').forEach(function(h){ rename(h, 'h4'); });
      art.querySelectorAll('h2').forEach(function(h){ rename(h, 'h3'); });
      return art.innerHTML;
    }).catch(function(){
      delete cache[id];
      return '<p class="anp-book-err">These notes could not be loaded. Check your connection and reload.</p>';
    });
    return cache[id];
  }
  function rename(el, tag){
    var n = el.ownerDocument.createElement(tag);
    for(var i = 0; i < el.attributes.length; i++) n.setAttribute(el.attributes[i].name, el.attributes[i].value);
    while(el.firstChild) n.appendChild(el.firstChild);
    el.parentNode.replaceChild(n, el);
  }

  /* The rail: open the chapter being shown, close the others. */
  function markRail(chId){
    rail.querySelectorAll('.tb-toc-mod').forEach(function(m){
      var head = m.querySelector('[data-book-ch]');
      var on = !!head && head.getAttribute('data-book-ch') === chId;
      m.classList.toggle('open', on);
      if(head){ if(on) head.setAttribute('aria-current', 'page'); else head.removeAttribute('aria-current'); }
    });
    var c = rail.querySelector('.tb-contents'), cur = c && c.querySelector('.open');
    if(cur && c.scrollHeight > c.clientHeight) c.scrollTop = Math.max(0, cur.offsetTop - c.offsetTop - 60);
  }

  // Focus moves to the new chapter's title only when the reader switched
  // chapters, not on the first load, so a screen reader starts at the top.
  var shown = null, moved = false;
  function show(chId, topicId){
    var ch = chById[chId];
    if(!ch) return;
    store(LAST, chId);
    markRail(chId);
    if(shown !== chId){
      shown = chId;
      var ts = builtOf(chId), i = chapters.indexOf(ch);
      var prev = chapters[i - 1], next = chapters[i + 1];
      var link = function(c, dir){
        if(!c || !builtOf(c.id).length) return '';
        return '<a class="tb-chapter-link' + (dir === 'next' ? ' next' : '') + '" href="#' + c.id + '"><span>' +
          (dir === 'next' ? 'Chapter ' + c.n + ' &rarr;' : '&larr; Chapter ' + c.n) + '</span><b>' + esc(c.title) + '</b></a>';
      };
      book.innerHTML =
        '<header class="tb-chapter-head anp-chap-head"><div>' +
          '<p class="tb-chapter-eyebrow">Chapter ' + ch.n + ' of ' + chapters.length + ' &middot; ' + esc(partTitle[ch.part] || '') + '</p>' +
          '<h1 class="tb-chapter-title" tabindex="-1">' + esc(ch.title) + '</h1>' +
          '<p class="tb-chapter-meta">' + ts.length + ' topics &middot; A&amp;P ' + esc(ch.course) + ' &middot; <span data-chap-meta="' + ch.id + '">not practiced yet</span></p>' +
        '</div><p class="anp-chap-acts"><a class="anp-tb-btn solid" href="practice.html?chapter=' + ch.id + '">Chapter quiz</a><a class="anp-tb-btn ghost" href="chapters/' + ch.id + '.html">Chapter page</a></p></header>' +
        ts.map(function(t){
          // Hidden until its prose and every earlier topic's has arrived, so
          // a topic landing never pushes the ones below it down the screen
          // (audit 2026-10, layout shift: CLS 0.57 on a phone).
          return '<section class="anp-book-sec" id="' + t.id + '" aria-labelledby="h-' + t.id + '" hidden>' +
            '<div class="anp-book-head"><h2 id="h-' + t.id + '"><span class="anp-toc-n">' + t.n + '</span>' + esc(t.title) + '</h2>' +
            '<div class="anp-book-acts"><span class="anp-tb-chip" data-chip-topic="' + t.id + '">Not practiced</span>' +
            '<a class="anp-tb-btn solid" href="lessons/' + t.id + '.html" aria-label="Lesson: ' + esc(t.title) + '">Lesson</a></div></div>' +
            '<div class="anp-prose" data-book-t="' + t.id + '"><p class="anp-book-wait">Loading&hellip;</p></div></section>';
        }).join('') +
        '<nav class="tb-chapter-nav anp-nav-ref" aria-label="Chapter navigation" hidden>' + link(prev, 'prev') + link(next, 'next') + '</nav>';
      if(window.AnpToc) window.AnpToc.paint();
      var ready = {};
      var reveal = function(){
        if(shown !== chId) return;
        for(var k = 0; k < ts.length; k++){
          if(!ready[ts[k].id]) return;
          var sec = document.getElementById(ts[k].id);
          if(sec) sec.hidden = false;
        }
        var nav = book.querySelector('.tb-chapter-nav');
        if(nav) nav.hidden = false;
      };
      var loads = ts.map(function(t){
        return prose(t.id).then(function(html){
          var slot = book.querySelector('[data-book-t="' + t.id + '"]');
          if(slot && shown === chId) slot.innerHTML = html;
          ready[t.id] = true;
          reveal();
        });
      });
      Promise.all(loads).then(function(){ reveal(); if(shown === chId && topicId) jump(topicId); });
    }
    if(topicId) jump(topicId);
    else if(moved){ window.scrollTo(0, 0); var h = book.querySelector('h1'); if(h) h.focus({ preventScroll: true }); }
  }
  function jump(id){
    var el = document.getElementById(id);
    if(el) el.scrollIntoView({ block: 'start' });
  }

  function route(){
    var h = decodeURIComponent(location.hash.slice(1));
    var t = tById[h];
    if(t && t.built) return show(t.chapter, t.id);
    if(chById[h] && builtOf(h).length) return show(h);
    var last = store(LAST);
    show(chById[last] && builtOf(last).length ? last : chapters.filter(function(c){ return builtOf(c.id).length; })[0].id);
  }

  /* Rail links stay real links (notes and chapter pages) for a reader without
     JavaScript; here they open the chapter in place instead. */
  rail.addEventListener('click', function(e){
    var a = e.target.closest('a');
    if(!a || e.metaKey || e.ctrlKey || e.shiftKey || e.button) return;
    var ch = a.getAttribute('data-book-ch'), t = a.getAttribute('data-toc-t');
    if(!ch && !t) return;
    e.preventDefault();
    document.body.classList.remove('tb-toc-open');
    var btn = document.querySelector('.tb-toc-btn');
    if(btn) btn.setAttribute('aria-expanded', 'false');
    var target = '#' + (t || ch);
    moved = true;
    if(location.hash === target) route(); else location.hash = target;
  });
  window.addEventListener('hashchange', function(){ moved = true; route(); });

  /* A&P I / II filter: hides the other course's chapters in the rail. */
  var sel = document.getElementById('course-filter');
  if(sel) sel.addEventListener('change', function(){
    rail.querySelectorAll('.tb-toc-mod[data-course]').forEach(function(m){
      var c = m.getAttribute('data-course');
      m.hidden = !!(sel.value && c && c !== sel.value);
    });
  });

  route();
})();
