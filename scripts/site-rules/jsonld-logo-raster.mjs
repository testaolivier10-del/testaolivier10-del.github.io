/* A structured-data logo is a raster image that exists, and the hub's
   Organization names a founder and a contact.

   Audit finding (site audit 2026-10, SEO): index.html's Organization logo was
   an SVG (Google wants PNG/JPG/WebP, 112 px or more) and it had no founder or
   contact. The hub's structured data is generated by scripts/build-pricing.mjs. */
import { readFileSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

function logos(node, out) {
  if (Array.isArray(node)) { for (const n of node) logos(n, out); return out; }
  if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      if (k === 'logo') out.push(typeof v === 'string' ? v : v && v.url);
      else logos(v, out);
    }
  }
  return out;
}

export default function ({ ROOT, fail, htmlFiles }) {
  for (const file of htmlFiles) {
    const rel = relative(ROOT, file).split(sep).join('/');
    if (rel.startsWith('scripts/') || rel.startsWith('docs/')) continue;
    const html = readFileSync(file, 'utf8');
    if (!html.includes('"logo"')) continue;
    for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
      let ld;
      try { ld = JSON.parse(m[1]); } catch { continue; } // section 2 reports bad JSON
      for (const url of logos(ld, [])) {
        if (!url || !/\.(png|jpe?g|webp)$/i.test(url)) { fail(`jsonld-logo-raster: ${rel} logo "${url}" is not a PNG, JPG or WebP.`); continue; }
        const p = url.replace(/^https:\/\/levlprep\.com\//, '');
        if (!existsSync(join(ROOT, p))) fail(`jsonld-logo-raster: ${rel} logo ${url} does not exist.`);
      }
      if (rel === 'index.html') {
        const org = (ld['@graph'] || [ld]).find((n) => n['@type'] === 'Organization');
        // No founder on purpose: the operator stays anonymous (2026-10-06). A contact is still required.
        if (org && !org.contactPoint) fail('jsonld-logo-raster: index.html Organization needs a contactPoint (scripts/build-pricing.mjs).');
        if (org && org.founder) fail('jsonld-logo-raster: index.html Organization must not name a founder; the operator stays anonymous.');
        if (!(ld['@graph'] || []).some((n) => n['@type'] === 'FAQPage')) fail('jsonld-logo-raster: index.html lost its FAQPage (scripts/build-pricing.mjs).');
      }
    }
  }
}
