/* Writes assets/from-video.js, the homepage card for visitors from TikTok and
   Instagram, from docs/from-video.json.

     node scripts/build-from-video.mjs           write the file
     node scripts/build-from-video.mjs --check   fail if the data is wrong or the file is stale (CI)

   index.html keeps only a one-line check inline (a tt- or ig- ref, or those
   apps' own browsers); only then does it load this file, so every other
   visitor downloads nothing extra. docs/from-video.md explains it. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DATA = 'docs/from-video.json';
export const OUT = 'assets/from-video.js';
const COURSES = {
  nremt: 'NREMT-EMT', ochem: 'Organic Chemistry', anp: 'Anatomy & Physiology', apbio: 'AP® Biology',
  apchem: 'AP® Chemistry', apphys: 'AP® Physics 1', apcalc: 'AP® Calculus AB', apstat: 'AP® Statistics',
  apenv: 'AP® Environmental Science',
  appsych: 'AP® Psychology',
  apprecalc: 'AP® Precalculus',
};

const CSS = `.from-video{margin:0 0 18px;max-width:520px;padding:14px 16px 16px;border:var(--bw,2px) solid var(--line);border-radius:var(--radius);background:var(--white);box-shadow:var(--lift-sm,none);}
.from-video .fv-k{margin:0;font:900 11.5px/1.3 var(--font-ui);letter-spacing:.07em;text-transform:uppercase;color:var(--accent-text);}
.from-video .fv-t{margin:2px 0 10px;font:900 19px/1.3 var(--font-display);color:var(--ink);}
.fv-item{display:flex;flex-direction:column;gap:3px;margin-top:8px;padding:12px 14px;min-height:48px;border-radius:12px;text-decoration:none;border:var(--bw,2px) solid var(--line);color:var(--ink);background:var(--ctint,var(--white));}
.fv-item b{font:900 16px/1.3 var(--font-ui);}
.fv-item small{font:700 13px/1.4 var(--font-ui);color:var(--muted);}
.fv-item.is-new{background:var(--navy);border-color:var(--navy);color:var(--on-accent);}
.fv-item.is-new small{color:inherit;opacity:.85;}
.fv-item:hover{border-color:var(--accent);}
.fv-item.is-new:hover{background:var(--navy2);}`;

export function validate(data, root = ROOT) {
  const errs = [];
  if (!data || !Array.isArray(data.videos)) return [`${DATA}: needs a "videos" list`];
  let last = '';
  for (const v of data.videos) {
    const w = `${DATA} ${v && v.date} ${v && v.topic}`;
    if (!/^\d{4}-\d{2}-\d{2}$/.test(v.date || '')) errs.push(`${w}: date must be YYYY-MM-DD`);
    else if (v.date < last) errs.push(`${w}: keep the list in date order`);
    last = v.date || last;
    if (!COURSES[v.course]) errs.push(`${w}: unknown course "${v.course}"`);
    for (const k of ['topic', 'hook']) {
      if (typeof v[k] !== 'string' || !v[k].trim() || v[k].length > 90) errs.push(`${w}: ${k} must be 1 to 90 characters`);
      else if (/[<>—–]|\s-\s/.test(v[k])) errs.push(`${w}: ${k} must be plain text with no dashes as punctuation`);
    }
    if (!/^[a-z0-9/-]+\.html$/.test(v.page || '') || !existsSync(join(root, v.page))) errs.push(`${w}: page ${v.page} does not exist`);
  }
  return errs;
}

export function render(data) {
  const list = data.videos.map((v) => ({ d: v.date, c: COURSES[v.course], t: v.topic, h: v.hook, p: '/' + v.page }));
  return `/* GENERATED by scripts/build-from-video.mjs from ${DATA}; edit there. Loaded by index.html only for
   visitors from TikTok or Instagram (docs/from-video.md). Shows the newest 3 Shorts whose posting time has
   come (6pm local time on the posting day), newest first. */
(function(){
  var V = ${JSON.stringify(list)};
  var CSS = ${JSON.stringify(CSS)};
  var host = document.getElementById('fromVideo');
  if(!host) return;
  try{
    var now = new Date(), p2 = function(n){ return (n < 10 ? '0' : '') + n; };
    var today = now.getFullYear() + '-' + p2(now.getMonth() + 1) + '-' + p2(now.getDate());
    var list = V.filter(function(v){ return v.d < today || (v.d === today && now.getHours() >= 18); }).slice(-3).reverse();
    if(!list.length){ host.className = ''; return; }
    var st = document.createElement('style'); st.textContent = CSS; document.head.appendChild(st);
    var box = document.createElement('section');
    box.className = 'from-video'; box.setAttribute('aria-label', 'From our videos');
    var k = document.createElement('p'); k.className = 'fv-k'; k.textContent = 'From our videos'; box.appendChild(k);
    var t = document.createElement('p'); t.className = 'fv-t'; t.textContent = 'Pick up where the video left off'; box.appendChild(t);
    list.forEach(function(v, i){
      var a = document.createElement('a'), b = document.createElement('b'), s = document.createElement('small');
      a.className = 'fv-item' + (i === 0 ? ' is-new' : ''); a.href = v.p;
      b.textContent = v.t;
      s.textContent = v.c + ' \\u00b7 the video: \\u201c' + v.h + '\\u201d';
      a.appendChild(b); a.appendChild(s);
      a.addEventListener('click', function(){ try{ window.LevlAnalytics && window.LevlAnalytics.event('from-video-open', { course: v.c, at: i + 1 }); }catch(e){} });
      box.appendChild(a);
    });
    host.appendChild(box);
    host.className = '';
  }catch(e){ host.className = ''; }
})();
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  const data = JSON.parse(readFileSync(join(ROOT, DATA), 'utf8'));
  const errs = validate(data);
  if (errs.length) { for (const e of errs) console.error(`FAIL: ${e}`); process.exit(1); }
  const want = render(data);
  const have = existsSync(join(ROOT, OUT)) ? readFileSync(join(ROOT, OUT), 'utf8') : '';
  if (want !== have) {
    if (check) { console.error(`FAIL: ${OUT} does not match ${DATA}. Run: node scripts/build-from-video.mjs`); process.exit(1); }
    writeFileSync(join(ROOT, OUT), want);
    console.log(`${OUT} written: ${data.videos.length} video topics.`);
  } else console.log(`OK: ${data.videos.length} video topics in ${OUT}.`);
}
