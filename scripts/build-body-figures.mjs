/* Body figures for the NREMT tools, rendered from the body map's 3D model.

   The scenario sim's "Assess the patient", the body map's Burns mode and the
   sound trainer's chest used to draw the patient from circles and rectangles.
   This renders the real BodyParts3D model (nremt/assets/body3d.glb) with the
   vendored three.js in headless chromium instead, and writes:

     nremt/assets/body-figs/<name>.webp   the shaded figures (transparent)
     nremt/assets/body-figs/<name>-anat.webp  the whole-body figures' anatomy
                                          view (the body map's look), same frame
     nremt/assets/body-figs/body.js       the whole-body figures' data and
     nremt/assets/body-figs/chest.js      the chest views': size, outline path,
                                          region paths and landmark positions,
                                          in each image's own pixels
   nremt/assets/body-figures.js (hand-written) is the small loader the tools
   use: LevlBodyFigs.load('body' | 'chest', cb).

   Every region boundary and listening site comes from measured anatomy: the
   rib ends, sternum, clavicles, scapulae, vertebrae and pelvis are read from
   the skeleton meshes and projected with the figure's own camera
   (scripts/body-figures/render.js has the method). Nothing is placed by eye.

   License: the figures are derived from BodyParts3D, (c) 2008 Life Science
   Integrated Database Center, CC BY-SA 2.1 Japan, and carry the same license; each page
   that shows them credits it.

     node scripts/build-body-figures.mjs           write
     node scripts/build-body-figures.mjs --check   fail if the data files are stale
     node scripts/build-body-figures.mjs --preview <dir>   also write overlay previews

   --check re-renders, so it needs chromium (CHROMIUM_PATH, or playwright's
   own). Rendering is deterministic for the data file; the WebP bytes can differ
   by encoder, so --check compares the data only. */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT_DIR = join(ROOT, 'nremt/assets/body-figs');
const args = process.argv.slice(2);
const check = args.includes('--check');
const previewDir = args.includes('--preview') ? args[args.indexOf('--preview') + 1] : null;

const { chromium } = await import('playwright');
const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
  args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader']
});
const page = await browser.newPage({ viewport: { width: 800, height: 800 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const TYPES = { '.js': 'text/javascript', '.html': 'text/html', '.glb': 'model/gltf-binary' };
await page.route('http://fig.local/**', r => {
  const p = decodeURIComponent(new URL(r.request().url()).pathname);
  if (p === '/index.html') return r.fulfill({ contentType: 'text/html', body:
    '<!doctype html><script type="importmap">{"imports":{"three":"/nremt/assets/vendor/three/build/three.module.min.js"}}</script>' +
    '<script type="module" src="/scripts/body-figures/render.js"></script>' });
  const f = join(ROOT, p);
  if (!f.startsWith(ROOT) || !existsSync(f)) return r.fulfill({ status: 404, body: '' });
  return r.fulfill({ body: readFileSync(f), contentType: TYPES[extname(f)] || 'application/octet-stream' });
});
await page.goto('http://fig.local/index.html');
await page.waitForFunction(() => typeof window.renderFigures === 'function', null, { timeout: 30000 });
const figs = await page.evaluate(() => window.renderFigures());
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const VERSION = 1;
const data = { version: VERSION, credit: 'BodyParts3D, (c) 2008 Life Science Integrated Database Center, CC BY-SA 2.1 Japan', figs: {} };
const images = {};
for (const [name, f] of Object.entries(figs)) {
  if (name.startsWith('_')) continue;
  images[name] = Buffer.from(f.webp.split(',')[1], 'base64');
  const { webp, anatWebp, ...rest } = f;
  data.figs[name] = { src: 'body-figs/' + name + '.webp', ...rest };
  // the anatomy view (translucent skin over skeleton and organs), same frame and pixels
  if(anatWebp){ images[name + '-anat'] = Buffer.from(anatWebp.split(',')[1], 'base64'); data.figs[name].anat = 'body-figs/' + name + '-anat.webp'; }
}
/* Two data files, so each tool fetches only its own: the whole-body figures
   (Burns, the scenario sim) and the chest views (the sound trainer). They are
   loaded on demand by LevlBodyFigs.load(set, cb) below, not by a script tag,
   so they are not on any page's first-load bill. */
const SETS = { body: n => !n.startsWith('chest-'), chest: n => n.startsWith('chest-') };
const HEAD = '/* Generated by scripts/build-body-figures.mjs from nremt/assets/body3d.glb. Do not edit.\n' +
  '   Figures derived from BodyParts3D, (c) 2008 Life Science Integrated Database Center, licensed CC BY-SA 2.1 Japan\n' +
  '   (https://creativecommons.org/licenses/by-sa/2.1/jp/deed.en); the images in body-figs/ carry the same license.\n' +
  '   Coordinates are in each image\'s own pixels. */\n';
const files = {};
for (const [set, keep] of Object.entries(SETS)) {
  const figsOf = Object.fromEntries(Object.entries(data.figs).filter(([n]) => keep(n)));
  files[join(OUT_DIR, set + '.js')] = HEAD + 'LevlBodyFigs.add(' + JSON.stringify({ version: VERSION, credit: data.credit, figs: figsOf }) + ');\n';
}
const outFiles = Object.keys(files);
const js = outFiles.map(f => files[f]).join('');

if (check) {
  const stale = outFiles.filter(f => !existsSync(f) || readFileSync(f, 'utf8') !== files[f]);
  const missing = Object.keys(images).filter(n => !existsSync(join(OUT_DIR, n + '.webp')));
  await browser.close();
  if (stale.length || missing.length) {
    console.error('body figure data is stale' + (missing.length ? ' (missing ' + missing.join(', ') + ')' : '') + ': run node scripts/build-body-figures.mjs');
    process.exit(1);
  }
  console.log('body figures up to date');
  process.exit(0);
}

mkdirSync(OUT_DIR, { recursive: true });
for (const [n, b] of Object.entries(images)) writeFileSync(join(OUT_DIR, n + '.webp'), b);
for (const f of outFiles) writeFileSync(f, files[f]);
console.log('wrote', Object.keys(images).map(n => n + ' ' + (images[n].length / 1024).toFixed(1) + ' KB').join(', '), '; data', (js.length / 1024).toFixed(1), 'KB');

if (previewDir) {
  mkdirSync(previewDir, { recursive: true });
  for (const [name, f] of Object.entries(data.figs)) {
    const regs = Object.entries(f.regions || {}).map(([k, d], i) =>
      `<path d="${d}" fill="hsla(${i * 67},85%,50%,.35)" stroke="hsl(${i * 47},80%,35%)" stroke-width="1.5" clip-path="url(#c)"/>`).join('');
    const lms = Object.entries(f.landmarks || {}).filter(([, v]) => Array.isArray(v) && typeof v[0] === 'number' && v.length === 2)
      .map(([k, v]) => `<circle cx="${v[0]}" cy="${v[1]}" r="5" fill="#06c"/><text x="${v[0] + 7}" y="${v[1] + 4}" font-size="12">${k}</text>`).join('');
    const html = `<body style="margin:0;background:#f4efe9"><svg width="${f.w}" height="${f.h}" viewBox="0 0 ${f.w} ${f.h}">
      <defs><clipPath id="c"><path d="${f.outline}"/></clipPath></defs>
      <image href="data:image/webp;base64,${images[name].toString('base64')}" width="${f.w}" height="${f.h}"/>
      <path d="${f.outline}" fill="none" stroke="#333" stroke-width="1"/>${regs}${lms}</svg></body>`;
    await page.setContent(html);
    await page.setViewportSize({ width: f.w, height: f.h });
    await page.screenshot({ path: join(previewDir, name + '.png') });
  }
}
await browser.close();
