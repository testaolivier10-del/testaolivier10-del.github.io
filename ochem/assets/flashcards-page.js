/* Drives flashcards.html — the ochem flashcard deck.

   WHERE THE CARDS COME FROM
   -------------------------
   Nothing here is a hand-typed copy of the course:
     - Concept cards are assembled right here from concepts.js (the title and
       its one-line hint) and concept-teach.json (the micro-lesson Practice
       shows after a mistake) — one card per concept.
     - Everything else is assets/flashcards.json, generated by
       scripts/build-flashcards.mjs out of the tables in the notes, plus a
       short authored list of named reactions (scripts/lib/flashcard-sources.mjs).
   Each card belongs to a curriculum topic, which gives it its chapter (for
   the filter) and its way back to the section and lesson that teach it.

   WHAT THIS FILE OWNS
   -------------------
   The deck view (filters, what is due), the session loop, and input: click
   or tap to flip, Space/Enter, 1-4 to grade, and a horizontal swipe on a
   phone. When a card comes back is flashcard-scheduler.js's business; XP is
   ochem-xp.js's (onCards), and it pays only for scheduled cards.

   Kept out of an inline <script> for the same reason as the other page
   scripts: the CI link checker scans .html for literal href/src paths, and
   this builds hrefs from data. */
(function(){
  var S  = window.OchemCardScheduler;
  var C  = window.OchemCurriculum;
  var CO = window.OchemConcepts;
  var M  = window.OchemMastery;

  var homeEl    = document.getElementById('fcHome');
  var heroEl    = document.getElementById('fcHero');
  var sessionEl = document.getElementById('fcSession');
  var doneEl    = document.getElementById('fcDone');
  var stageEl   = document.getElementById('fcStage');
  var modeEl    = document.getElementById('fcMode');
  var quitBtn   = document.getElementById('fcQuit');
  var progFill  = document.getElementById('fcProgFill');
  var progLabel = document.getElementById('fcProgLabel');
  var liveEl    = document.getElementById('fcLive');
  if(!homeEl || !S || !C) return;

  var PREFS_KEY = 'ochem_flashcards_prefs';   // per-browser view settings; not synced
  var AHEAD_SIZE = 20;                         // cards in one study-ahead run
  var AGAIN_GAP = 3;                           // a missed card returns this many cards later
  var LONG_TEACH = 700;                        // characters; smaller type beyond this

  var TYPE_LABEL = { concept: 'Concept', table: 'Fact', authored: 'Named reaction' };

  function esc(s){
    return String(s == null ? '' : s)
      .replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
  }
  function plural(n, w, ws){ return n + ' ' + (n === 1 ? w : (ws || w + 's')); }
  function reducedMotion(){
    try{ return window.matchMedia('(prefers-reduced-motion: reduce)').matches; }catch(e){ return false; }
  }

  /* ---- the curriculum index ------------------------------------------ */

  var TOPIC = {};        // topic id -> { topic, mod, modIndex, order }
  var n = 0;
  C.MODULES.forEach(function(mod, i){
    mod.topics.forEach(function(t){ TOPIC[t.id] = { topic: t, mod: mod, modIndex: i, order: n++ }; });
  });

  /* ---- preferences (this browser only) --------------------------------- */

  var prefs = { chapter: 'all', scope: 'all', types: { concept: true, table: true, authored: true } };
  try{
    var saved = JSON.parse(localStorage.getItem(PREFS_KEY) || 'null');
    if(saved && typeof saved === 'object'){
      if(typeof saved.chapter === 'string') prefs.chapter = saved.chapter;
      if(saved.scope === 'studied' || saved.scope === 'weak' || saved.scope === 'all') prefs.scope = saved.scope;
      if(saved.types && typeof saved.types === 'object'){
        ['concept', 'table', 'authored'].forEach(function(k){ if(typeof saved.types[k] === 'boolean') prefs.types[k] = saved.types[k]; });
      }
    }
  }catch(e){}
  // A link can open the deck on one chapter or one topic: ?chapter=<module id>
  // or ?topic=<topic id>. The topic filter is for this visit only.
  var onlyTopic = null;
  try{
    var params = new URLSearchParams(location.search);
    var ch = params.get('chapter'), tp = params.get('topic');
    if(ch && C.MODULES.some(function(m){ return m.id === ch; })) prefs.chapter = ch;
    if(tp && TOPIC[tp]){ onlyTopic = tp; prefs.chapter = TOPIC[tp].mod.id; }
  }catch(e){}
  if(prefs.chapter !== 'all' && !C.MODULES.some(function(m){ return m.id === prefs.chapter; })) prefs.chapter = 'all';
  function savePrefs(){
    try{ localStorage.setItem(PREFS_KEY, JSON.stringify(prefs)); }catch(e){}
  }

  /* ---- the deck ---------------------------------------------------------- */

  var DECK = [];
  var BY_ID = {};

  function addCard(c, rank, i){
    var where = TOPIC[c.topic];
    if(!where) return;          // a topic that left the curriculum takes its cards with it
    c.modIndex = where.modIndex;
    c.modId = where.mod.id;
    c.sort = where.order * 10000 + rank * 1000 + i;
    DECK.push(c);
    BY_ID[c.id] = c;
  }

  function buildDeck(data){
    DECK = []; BY_ID = {};
    (CO ? CO.ALL : []).forEach(function(c, i){
      addCard({
        id: 'c:' + c.id, topic: (c.topics || [])[0], src: 'concept', kind: 'concept',
        ask: 'Concept · ' + c.family + ' — explain it, then flip.',
        title: c.title, hint: c.hint || '', teach: c.teach || ''
      }, 0, i);
    });
    ((data && data.cards) || []).forEach(function(c, i){
      addCard(c, c.src === 'authored' ? 1 : 2, i);
    });
    DECK.sort(function(a, b){ return a.sort - b.sort; });
  }

  // Concept teach strings arrive with concept-teach.json; attachTeach() puts
  // them on the concept records, and this copies them onto the cards.
  function refreshTeach(){
    if(!CO) return;
    DECK.forEach(function(card){
      if(card.src !== 'concept') return;
      var c = CO.get(card.id.slice(2));
      if(c && c.teach) card.teach = c.teach;
    });
  }

  /* ---- studied / needs work ------------------------------------------------
     What the course already knows about you, per topic. "Studied" is any
     honest sign you have been there: a section read, a lesson worked, a
     question answered under that topic, or a card from it already learned.
     "Needs work" is weakness the course has measured — the concept model
     under 70% (the line the Review page draws between shaky and solid), a
     lesson run under 60% over 5+ attempts (curriculum.js's struggling line),
     an unresolved missed question — or a card you keep forgetting. */

  function readJson(key){
    try{ return JSON.parse(localStorage.getItem(key) || 'null') || {}; }catch(e){ return {}; }
  }

  function topicSignals(){
    var progress = readJson('ochem_progress');
    var read = readJson('ochem_textbook_read');
    var studied = {}, weak = {};
    Object.keys(TOPIC).forEach(function(t){
      var p = progress[t];
      if(read[t] || (p && (p.attempts > 0 || p.completed))) studied[t] = true;
      if(p && p.attempts >= 5 && p.correct / p.attempts < 0.6) weak[t] = true;
      if(M && M.topicStrength){
        var r = M.topicStrength(t);
        if(r.attempts > 0) studied[t] = true;
        if(r.strength !== null && r.strength < 0.70) weak[t] = true;
      }
    });
    if(M && M.mistakes){
      M.mistakes({ limit: 120 }).forEach(function(m){ if(m.topicId && TOPIC[m.topicId]){ weak[m.topicId] = true; studied[m.topicId] = true; } });
    }
    return { studied: studied, weak: weak };
  }

  function conceptWeak(card){
    if(!M || card.src !== 'concept') return null;
    var p = M.profile(card.id.slice(2));
    if(!p || !p.attempts) return null;
    return p.attempts >= 3 && p.strength !== null && p.strength < 0.70;
  }

  function classify(){
    var sig = topicSignals();
    var store = S.load();
    DECK.forEach(function(card){
      var st = store.cards[card.id];
      var learned = !S.isNew(st);
      var cw = conceptWeak(card);
      card.studied = learned || !!sig.studied[card.topic] ||
        (card.src === 'concept' && M ? M.profile(card.id.slice(2)).attempts > 0 : false);
      card.weak = cw === true || (cw === null && !!sig.weak[card.topic]) ||
        (learned && ((st.l || 0) >= 2 || (st.l > 0 && st.i === 0)));
    });
  }

  function inScope(card, scope){
    if(scope === 'studied') return card.studied;
    if(scope === 'weak') return card.weak;
    return true;
  }
  function selection(opts){
    opts = opts || {};
    var chapter = opts.chapter === undefined ? prefs.chapter : opts.chapter;
    var scope = opts.scope === undefined ? prefs.scope : opts.scope;
    return DECK.filter(function(c){
      if(onlyTopic && c.topic !== onlyTopic) return false;
      if(!opts.anyType && !prefs.types[c.src]) return false;
      if(chapter !== 'all' && c.modId !== chapter) return false;
      return inScope(c, scope);
    });
  }
  function ids(cards){ return cards.map(function(c){ return c.id; }); }

  /* ---- the deck view --------------------------------------------------- */

  function show(view){
    homeEl.hidden    = view !== 'home';
    sessionEl.hidden = view !== 'session';
    doneEl.hidden    = view !== 'done';
    if(heroEl) heroEl.hidden = view !== 'home';
    window.scrollTo({ top: 0, behavior: 'auto' });
  }

  function chapterName(i){ return (i + 1) + ' · ' + C.MODULES[i].title; }

  function renderHome(){
    classify();
    var now = Date.now();
    var sel = selection();
    var q = S.queue(ids(sel), now);
    var html = '';

    if(onlyTopic){
      html += '<div class="next-up" style="margin-bottom:14px;">Showing only <b>' + esc(TOPIC[onlyTopic].topic.title) +
        '</b>. <button type="button" class="link-underline" id="fcAllTopics" style="background:none;border:0;padding:0;font:inherit;color:var(--accent-text);cursor:pointer;">Show the whole deck</button></div>';
    }

    var work = q.due.length + q.fresh.length;
    if(work){
      var parts = [];
      if(q.due.length) parts.push(plural(q.due.length, 'card') + ' due');
      if(q.fresh.length) parts.push(q.fresh.length + ' new');
      html += '<div class="rec-card">' +
        '<div class="k">' + (q.due.length ? 'Due now' : 'Ready to start') + '</div>' +
        '<h2>' + esc(parts.join(' · ')) + '</h2>' +
        '<p>' + esc(q.due.length
          ? 'Most overdue first, then new cards in course order. Anything you miss comes back a few cards later.'
          : 'New cards arrive ' + S.NEW_PER_DAY + ' a day, in course order, so the deck grows at a pace you can keep up with.') +
        '</p>' +
        '<div class="actions">' +
          '<button type="button" class="btn-press" id="fcStart">Start · ' + plural(work, 'card') + '</button>' +
          '<button type="button" class="btn-press alt" id="fcAhead">Study ahead</button>' +
        '</div></div>';
    } else if(sel.length){
      var up = S.upcoming(ids(sel), now, 7);
      var reason = q.newTotal && !q.allowance
        ? 'You have met today’s ' + S.NEW_PER_DAY + ' new cards. More arrive tomorrow.'
        : 'Nothing in this selection is due.';
      html += '<div class="empty-panel" style="margin-bottom:6px;">' +
        '<h2>All caught up</h2>' +
        '<p>' + esc(reason + (up ? ' ' + plural(up, 'card') + ' come' + (up === 1 ? 's' : '') + ' due in the next week.' : '')) +
        ' Studying ahead reviews cards early without pushing them further out.</p>' +
        '<div style="margin-top:18px"><button type="button" class="btn-press alt sm" id="fcAhead">Study ahead</button></div>' +
      '</div>';
    } else {
      html += '<div class="empty-panel" style="margin-bottom:6px;">' +
        '<h2>No cards in this selection</h2>' +
        '<p>' + esc(prefs.scope === 'studied'
          ? '“Studied” fills in as you read sections, work lessons and practice.'
          : prefs.scope === 'weak'
            ? '“Needs work” lists topics where practice, a lesson or your own cards say you are shaky. Nothing is, yet.'
            : 'Every card type is switched off.') + '</p>' +
      '</div>';
    }

    html += renderFilters(q);
    html += renderChapters();

    homeEl.innerHTML = html;
    bindHome();
    show('home');
  }

  function renderFilters(q){
    var anyScope = function(scope){ return selection({ scope: scope }).length; };
    var opts = '<option value="all"' + (prefs.chapter === 'all' ? ' selected' : '') + '>All chapters</option>' +
      C.MODULES.map(function(m, i){
        return '<option value="' + esc(m.id) + '"' + (prefs.chapter === m.id ? ' selected' : '') + '>' + esc(chapterName(i)) + '</option>';
      }).join('');
    function radio(value, label){
      return '<label><input type="radio" name="fcScope" value="' + value + '"' + (prefs.scope === value ? ' checked' : '') + '>' +
        '<span>' + esc(label) + ' <small>' + anyScope(value) + '</small></span></label>';
    }
    function box(key, label){
      return '<label><input type="checkbox" name="fcType" value="' + key + '"' + (prefs.types[key] ? ' checked' : '') + '>' +
        '<span>' + esc(label) + '</span></label>';
    }
    return '<div class="fc-filters" role="group" aria-label="Choose cards">' +
      '<label class="fc-field">Chapter<select id="fcChapter">' + opts + '</select></label>' +
      '<fieldset><legend>Topics</legend><div class="fc-seg">' +
        radio('all', 'All') + radio('studied', 'Studied') + radio('weak', 'Needs work') +
      '</div></fieldset>' +
      '<fieldset><legend>Card types</legend><div class="fc-seg">' +
        box('concept', 'Concepts') + box('table', 'Facts & values') + box('authored', 'Named reactions') +
      '</div></fieldset>' +
      '<p class="fc-note">' + esc(plural(q.total, 'card') + ' selected · ' + q.learned + ' learned · ' + q.newTotal + ' not seen yet.') + '</p>' +
    '</div>';
  }

  function renderChapters(){
    var now = Date.now();
    var store = S.load();
    var rows = C.MODULES.map(function(m, i){
      var cards = selection({ chapter: m.id });
      if(!cards.length) return '';
      var due = 0, learned = 0;
      cards.forEach(function(c){
        var st = store.cards[c.id];
        if(!S.isNew(st)){ learned++; if(st.d <= now) due++; }
      });
      var pct = Math.round(learned / cards.length * 100);
      return '<button type="button" class="fc-ch" data-ch="' + esc(m.id) + '" aria-pressed="' + (prefs.chapter === m.id) + '">' +
        '<span class="n"><b>' + (i + 1) + '</b>' + esc(m.title) + '</span>' +
        '<span class="c">' + (due ? '<span class="due">' + due + ' due</span> · ' : '') + learned + '/' + cards.length + '</span>' +
        '<span class="bar" aria-hidden="true"><span style="width:' + pct + '%"></span></span>' +
      '</button>';
    }).join('');
    if(!rows) return '';
    return '<div class="fc-label">By chapter</div><div class="module-card fc-chapters">' + rows + '</div>';
  }

  function bindHome(){
    var start = homeEl.querySelector('#fcStart');
    if(start) start.addEventListener('click', function(){ startSession('review'); });
    var ahead = homeEl.querySelector('#fcAhead');
    if(ahead) ahead.addEventListener('click', function(){ startSession('ahead'); });
    var all = homeEl.querySelector('#fcAllTopics');
    if(all) all.addEventListener('click', function(){
      onlyTopic = null;
      prefs.chapter = 'all';
      try{ history.replaceState(null, '', location.pathname); }catch(e){}
      renderHome();
    });
    var chSel = homeEl.querySelector('#fcChapter');
    chSel.addEventListener('change', function(){ prefs.chapter = chSel.value; savePrefs(); rerender('#fcChapter'); });
    homeEl.querySelectorAll('input[name=fcScope]').forEach(function(r){
      r.addEventListener('change', function(){ prefs.scope = r.value; savePrefs(); rerender('input[name=fcScope][value=' + r.value + ']'); });
    });
    homeEl.querySelectorAll('input[name=fcType]').forEach(function(b){
      b.addEventListener('change', function(){ prefs.types[b.value] = b.checked; savePrefs(); rerender('input[name=fcType][value=' + b.value + ']'); });
    });
    homeEl.querySelectorAll('.fc-ch').forEach(function(btn){
      btn.addEventListener('click', function(){
        var id = btn.getAttribute('data-ch');
        prefs.chapter = prefs.chapter === id ? 'all' : id;
        savePrefs();
        rerender('.fc-ch[data-ch="' + id + '"]');
      });
    });
  }
  // Re-render in place and put focus back on the control that changed, so a
  // keyboard user is not thrown back to the top of the page by a filter.
  function rerender(focusSel){
    var y = window.scrollY;
    renderHome();
    window.scrollTo({ top: y, behavior: 'auto' });
    var el = homeEl.querySelector(focusSel);
    if(el) el.focus({ preventScroll: true });
  }

  /* ---- the session ------------------------------------------------------ */

  var run = null;

  function shuffle(a){
    for(var i = a.length - 1; i > 0; i--){ var j = Math.floor(Math.random() * (i + 1)); var t = a[i]; a[i] = a[j]; a[j] = t; }
    return a;
  }

  function startSession(mode){
    classify();
    var now = Date.now();
    var sel = selection();
    var list;
    if(mode === 'review'){
      var q = S.queue(ids(sel), now);
      list = q.due.concat(q.fresh);
    } else {
      // Studying ahead: cards already learned but not due, shuffled; if the
      // selection has none, new ones in course order.
      var store = S.load();
      var learned = sel.filter(function(c){ var st = store.cards[c.id]; return !S.isNew(st) && !S.isDue(st, now); });
      list = learned.length ? ids(shuffle(learned)) : ids(sel.filter(function(c){ return S.isNew(store.cards[c.id]); }));
      list = list.slice(0, AHEAD_SIZE);
    }
    if(!list.length){ renderHome(); return; }
    var chapter = prefs.chapter === 'all' ? '' : ' · ' + C.MODULES.filter(function(m){ return m.id === prefs.chapter; })[0].title;
    run = {
      mode: mode, queue: list, total: list.length, done: 0, current: null, flipped: false,
      counts: { 1: 0, 2: 0, 3: 0, 4: 0 }, paid: {}, flushed: 0, seen: {}
    };
    modeEl.textContent = (mode === 'review' ? 'Review' : 'Studying ahead') + (onlyTopic ? ' · ' + TOPIC[onlyTopic].topic.title : chapter);
    show('session');
    nextCard();
  }

  function paidCount(){ return Object.keys(run.paid).length; }

  function nextCard(){
    if(!run.queue.length){ finish(true); return; }
    run.current = BY_ID[run.queue.shift()];
    if(!run.current){ nextCard(); return; }
    run.flipped = false;
    renderCard();
    var left = run.queue.length + 1;
    progFill.style.width = Math.round(run.done / (run.done + left) * 100) + '%';
    progLabel.textContent = left === 1 ? 'Last card' : left + ' left';
    liveEl.textContent = 'Card ' + (run.done + 1) + ', ' + left + ' left.';
    var flip = stageEl.querySelector('#fcFlipBtn');
    if(flip) flip.focus({ preventScroll: true });
  }

  function stateTag(card){
    var st = S.get(card.id), now = Date.now();
    if(S.isNew(st)) return 'New';
    if(S.isLearning(st)) return 'Learning';
    if(S.isDue(st, now)) return 'Due';
    return 'Ahead of schedule';
  }

  function metaHtml(card){
    var where = TOPIC[card.topic];
    return '<div class="fc-meta">' +
      '<span class="tag accent">Ch ' + (where.modIndex + 1) + ' · ' + esc(where.topic.title) + '</span>' +
      '<span class="tag good">' + esc(TYPE_LABEL[card.src] || 'Card') + '</span>' +
      '<span>' + esc(stateTag(card)) + '</span>' +
    '</div>';
  }

  function frontHtml(card){
    var q = card.src === 'concept' ? esc(card.title) : card.q;
    return '<div class="fc-face fc-front">' + metaHtml(card) +
      '<p class="fc-ask">' + esc(card.ask) + '</p>' +
      '<div class="fc-q">' + q + '</div>' +
      '<p class="fc-tap fc-swipe-hint">Tap to flip</p>' +
    '</div>';
  }

  function backHtml(card){
    var where = TOPIC[card.topic];
    var body;
    if(card.src === 'concept'){
      body = '<div class="fc-q">' + esc(card.title) + '</div>' +
        (card.hint ? '<p class="fc-hint">' + esc(card.hint) + '</p>' : '') +
        (card.teach ? '<p class="fc-teach' + (card.teach.length > LONG_TEACH ? ' long' : '') + '">' + esc(card.teach) + '</p>' : '');
    } else {
      body = '<div class="fc-q">' + card.q + '</div>' +
        '<dl class="fc-ans">' + card.a.map(function(row){
          return '<div>' + (row[0] ? '<dt>' + esc(row[0]) + '</dt>' : '') + '<dd>' + row[1] + '</dd></div>';
        }).join('') + '</dl>';
    }
    var lesson = C.hasLesson(where.topic) ? ' · <a href="' + esc(where.topic.href) + '">Open the lesson</a>' : '';
    var from = card.from ? 'From “' + esc(card.from) + '” in ' : 'Taught in ';
    return '<div class="fc-face fc-back" tabindex="-1" role="group" aria-label="Answer">' + metaHtml(card) + body +
      '<p class="fc-from">' + from + '<a href="learn.html#' + esc(card.topic) + '">' + esc(where.topic.title) + '</a>' + lesson + '</p>' +
    '</div>';
  }

  function controlsHtml(card){
    if(!run.flipped){
      return '<button type="button" class="btn-press wide fc-flip" id="fcFlipBtn">Show answer</button>' +
        '<p class="fc-keys"><kbd>Space</kbd> flip · <kbd>1</kbd>–<kbd>4</kbd> grade</p>' +
        '<p class="fc-keys fc-swipe-hint">After flipping: swipe right for Good, left for Again</p>';
    }
    var st = S.get(card.id), now = Date.now();
    var pv = S.preview(st, now, S.isEarly(st, now));
    return '<div class="fc-grades" role="group" aria-label="How well did you know it?">' +
      [1, 2, 3, 4].map(function(g){
        var label = S.GRADES[g].label;
        return '<button type="button" class="g' + g + '" data-grade="' + g + '" aria-label="' + label + ', next review ' + esc(pv[g]) + '">' +
          label + '<small>' + esc(pv[g]) + '</small></button>';
      }).join('') +
    '</div>' +
    '<p class="fc-keys"><kbd>1</kbd> Again · <kbd>2</kbd> Hard · <kbd>3</kbd> Good · <kbd>4</kbd> Easy · <kbd>Space</kbd> flip back</p>' +
    '<p class="fc-keys fc-swipe-hint">Swipe the card: right for Good, left for Again</p>';
  }

  function renderCard(){
    var card = run.current;
    stageEl.innerHTML = '<div class="fc-card" id="fcCard">' + (run.flipped ? backHtml(card) : frontHtml(card)) + '</div>' +
      '<div id="fcControls">' + controlsHtml(card) + '</div>';
    bindCard();
  }

  function bindCard(){
    var cardEl = stageEl.querySelector('#fcCard');
    var flipBtn = stageEl.querySelector('#fcFlipBtn');
    if(flipBtn) flipBtn.addEventListener('click', flip);
    stageEl.querySelectorAll('.fc-grades button').forEach(function(b){
      b.addEventListener('click', function(){ grade(+b.getAttribute('data-grade')); });
    });
    cardEl.addEventListener('click', function(e){
      if(swipe.suppressClick){ swipe.suppressClick = false; return; }
      if(e.target.closest('a, button')) return;
      // Selecting text on the answer to copy it should not flip it away.
      var s = window.getSelection && window.getSelection();
      if(s && String(s).length) return;
      flip();
    });
    bindSwipe(cardEl);
  }

  /* The turn: the face spins to edge-on, swaps, and spins back. Only one face
     is ever in the DOM, so the hidden side cannot be tabbed into or read out,
     and the card is as tall as what it is showing. Reduced motion swaps
     instantly. */
  var turning = false;
  function flip(){
    if(!run || !run.current || turning) return;
    var cardEl = stageEl.querySelector('#fcCard');
    var toBack = !run.flipped;
    function swap(){
      run.flipped = toBack;
      var card = run.current;
      cardEl.innerHTML = toBack ? backHtml(card) : frontHtml(card);
      stageEl.querySelector('#fcControls').innerHTML = controlsHtml(card);
      stageEl.querySelectorAll('.fc-grades button').forEach(function(b){
        b.addEventListener('click', function(){ grade(+b.getAttribute('data-grade')); });
      });
      var fb = stageEl.querySelector('#fcFlipBtn');
      if(fb) fb.addEventListener('click', flip);
      if(toBack){
        var back = cardEl.querySelector('.fc-back');
        if(back) back.focus({ preventScroll: true });
      } else if(fb){
        fb.focus({ preventScroll: true });
      }
    }
    if(reducedMotion()){ swap(); return; }
    turning = true;
    cardEl.classList.remove('is-turning');
    void cardEl.offsetWidth;          // restart the animation
    cardEl.classList.add('is-turning');
    setTimeout(swap, 160);            // halfway: edge-on, so the swap is invisible
    setTimeout(function(){ cardEl.classList.remove('is-turning'); turning = false; }, 330);
  }

  function grade(g){
    if(!run || !run.current || !run.flipped || turning) return;
    var card = run.current;
    var res = S.grade(card.id, g, Date.now(), { cram: run.mode === 'ahead' });
    run.counts[g]++;
    run.seen[card.id] = true;
    if(res.scheduled) run.paid[card.id] = true;
    if(g === S.AGAIN){
      // Back a few cards later, not immediately: straight away it would be
      // read off short-term memory, which proves nothing.
      run.queue.splice(Math.min(AGAIN_GAP, run.queue.length), 0, card.id);
    } else {
      run.done++;
    }
    nextCard();
  }

  /* ---- swipe --------------------------------------------------------------
     Horizontal drag on the card. On the question side any decisive swipe
     flips; on the answer side right is Good and left is Again, the two
     grades a thumb needs. Vertical movement is left to the page (touch-action:
     pan-y), and anything short of the threshold snaps back. */
  var swipe = { x: 0, y: 0, id: null, dx: 0, active: false, suppressClick: false };
  var SWIPE_MIN = 70;
  function bindSwipe(cardEl){
    cardEl.addEventListener('pointerdown', function(e){
      if(e.pointerType === 'mouse' || e.target.closest('a, button')) return;
      swipe.id = e.pointerId; swipe.x = e.clientX; swipe.y = e.clientY; swipe.dx = 0; swipe.active = true;
    });
    cardEl.addEventListener('pointermove', function(e){
      if(!swipe.active || e.pointerId !== swipe.id) return;
      swipe.dx = e.clientX - swipe.x;
      var dy = e.clientY - swipe.y;
      if(Math.abs(dy) > Math.abs(swipe.dx) && Math.abs(dy) > 12){ reset(); return; }
      if(!reducedMotion() && Math.abs(swipe.dx) > 6){
        cardEl.classList.add('is-dragging');
        var face = cardEl.firstElementChild;
        if(face) face.style.transform = 'translateX(' + swipe.dx + 'px) rotate(' + (swipe.dx / 40) + 'deg)';
      }
    });
    function reset(){
      swipe.active = false;
      cardEl.classList.remove('is-dragging');
      var face = cardEl.firstElementChild;
      if(face) face.style.transform = '';
    }
    cardEl.addEventListener('pointercancel', reset);
    cardEl.addEventListener('pointerup', function(e){
      if(!swipe.active || e.pointerId !== swipe.id) return;
      var dx = swipe.dx;
      reset();
      if(Math.abs(dx) < SWIPE_MIN) return;
      swipe.suppressClick = true;
      setTimeout(function(){ swipe.suppressClick = false; }, 400);
      if(!run.flipped) flip();
      else grade(dx > 0 ? S.GOOD : S.AGAIN);
    });
  }

  /* ---- keys ----------------------------------------------------------------- */

  document.addEventListener('keydown', function(e){
    if(!run || sessionEl.hidden || e.ctrlKey || e.metaKey || e.altKey) return;
    var t = e.target;
    var tag = t && t.tagName;
    if(tag === 'INPUT' || tag === 'SELECT' || tag === 'TEXTAREA' || (t && t.isContentEditable)) return;
    if(e.key === ' ' || e.key === 'Enter'){
      // A focused button or link already does its own thing with these keys.
      if(tag === 'BUTTON' || tag === 'A') return;
      e.preventDefault();
      flip();
    } else if(/^[1-4]$/.test(e.key) && run.flipped){
      e.preventDefault();
      grade(+e.key);
    }
  });

  /* ---- the end -------------------------------------------------------------- */

  // XP is settled when a run ends, and also if the page is left mid-run, so
  // closing the tab does not forfeit what was done. `flushed` keeps the two
  // from paying for the same cards.
  function settle(){
    if(!run) return null;
    var owed = paidCount() - run.flushed;
    if(owed <= 0 || !window.OchemXP) return null;
    run.flushed += owed;
    return window.OchemXP.onCards(owed);
  }
  window.addEventListener('pagehide', function(){ if(run && !sessionEl.hidden) settle(); });

  function finish(completed){
    if(!run) return;
    var reviewed = run.counts[1] + run.counts[2] + run.counts[3] + run.counts[4];
    settle();
    var r = run;
    var xpHtml = window.OchemXP && paidCount() ? window.OchemXP.summaryHtml() : '';
    if(window.LevlSound && reviewed) window.LevlSound.flourish(reviewed ? (r.counts[3] + r.counts[4]) / reviewed : 0);

    var now = Date.now();
    var sel = selection();
    var q = S.queue(ids(sel), now);
    var more = q.due.length + q.fresh.length;
    var tomorrow = S.upcoming(ids(sel), now, 2);   // through the end of tomorrow

    var line = reviewed
      ? plural(Object.keys(r.seen).length, 'card') + ': ' +
        [[4, 'Easy'], [3, 'Good'], [2, 'Hard'], [1, 'Again']].filter(function(x){ return r.counts[x[0]]; })
          .map(function(x){ return r.counts[x[0]] + ' ' + x[1]; }).join(', ') + '.'
      : 'No cards graded.';
    var note = r.mode === 'ahead'
      ? 'Studying ahead: cards you knew keep their schedule, anything you missed was brought forward. No XP for early reviews.'
      : (r.counts[1] ? 'Cards you missed are back on a short interval.' : 'Every card moved further out.');
    var html = xpHtml + '<div class="rec-card">' +
      '<div class="k">' + (completed ? 'Session done' : 'Session ended') + '</div>' +
      '<h2>' + esc(completed ? (r.mode === 'review' && !more ? 'That’s everything due.' : 'Done.') : 'Stopped early — the rest is still waiting.') + '</h2>' +
      '<p>' + esc(line + ' ' + note) + '</p>' +
      (tomorrow ? '<p>' + esc(plural(tomorrow, 'card') + ' due by tomorrow.') + '</p>' : '') +
      '<div class="actions">' +
        (more ? '<button type="button" class="btn-press" id="fcMore">Keep going · ' + plural(more, 'card') + '</button>' : '') +
        '<button type="button" class="btn-press alt" id="fcBack">Back to the deck</button>' +
      '</div></div>';
    run = null;
    doneEl.innerHTML = html;
    show('done');
    var m = doneEl.querySelector('#fcMore');
    if(m) m.addEventListener('click', function(){ startSession('review'); });
    doneEl.querySelector('#fcBack').addEventListener('click', renderHome);
    var focusTo = m || doneEl.querySelector('#fcBack');
    if(focusTo) focusTo.focus({ preventScroll: true });
  }

  quitBtn.addEventListener('click', function(){ finish(false); });

  /* ---- boot ------------------------------------------------------------------ */

  homeEl.innerHTML = '<div class="empty-panel"><h2>Shuffling the deck…</h2></div>';
  var deckReady = fetch('assets/flashcards.json').then(function(res){
    if(!res.ok) throw new Error('flashcards.json ' + res.status);
    return res.json();
  });
  var teachReady = CO && CO.loadTeach ? CO.loadTeach('assets/concept-teach.json') : Promise.resolve();

  deckReady.then(function(data){
    buildDeck(data);
    refreshTeach();
    renderHome();
    // The micro-lessons may land after the deck; copy them over when they do.
    teachReady.then(function(){ refreshTeach(); if(run && run.flipped) renderCard(); });
  }, function(err){
    // The concept cards need nothing fetched but their teach text, so a
    // failed deck file still leaves a usable (smaller) deck.
    if(window.console && console.warn) console.warn('Flashcard deck file unavailable; concept cards only.', err);
    buildDeck(null);
    teachReady.then(function(){ refreshTeach(); renderHome(); });
  });
})();
